#: Fixed identifier, so building and rendering agree without arguments.
REFERENCE_PROJECT_ID = "reference-engineering-fixture"
REFERENCE_TITLE = "Polymation Engineering Reference"
REFERENCE_SLUG = "polymation-engineering-reference"

FPS = 30
SAMPLE_RATE = 48_000

#: Scene lengths in frames. Six narrative scenes totalling 5400 frames, which
#: is exactly 180.0 seconds at 30 fps — chosen to land on a whole second so the
#: duration assertion needs no tolerance for the target itself.
SCENE_FRAMES: tuple[int, ...] = (780, 960, 1020, 900, 960, 780)

#: Frames, within each scene, carrying a visual sync marker. One near the start
#: of every scene plus one mid-way through the longest, giving markers spread
#: across the whole timeline.
SCENE_MARKER_FRAMES: tuple[tuple[int, ...], ...] = (
    (6,),
    (6, 480),
    (6, 510),
    (6,),
    (6, 480),
    (6,),
)


@dataclass
class ReferenceBuild:
    """What building the reference fixture produced."""

    bundle: ProjectBundle
    generated_assets: list[Path] = field(default_factory=list)
    recreated: bool = False

    @property
    def total_frames(self) -> int:
        """Length of the compiled timeline in frames."""
        return self.bundle.timeline.total_frames if self.bundle.timeline else 0

    @property
    def duration_seconds(self) -> float:
        """Length of the compiled timeline in seconds."""
        return self.total_frames / FPS

    def to_dict(self) -> dict[str, Any]:
        """JSON-serialisable form."""
        timeline = self.bundle.timeline
        return {
            "project_id": self.bundle.project_id,
            "path": str(self.bundle.root),
            "recreated": self.recreated,
            "generated_assets": [str(path) for path in self.generated_assets],
            "scene_count": len(timeline.scenes) if timeline else 0,
            "shot_count": timeline.shot_count if timeline else 0,
            "overlay_count": timeline.overlay_count if timeline else 0,
            "audio_segment_count": len(timeline.audio.segments) if timeline else 0,
            "total_frames": self.total_frames,
            "duration_seconds": self.duration_seconds,
            "marker_seconds": [round(value, 4) for value in marker_times()],
        }


def scene_offset(index: int) -> int:
    """Absolute start frame of scene ``index``."""
    return sum(SCENE_FRAMES[:index])


def marker_frames() -> list[int]:
    """Absolute frame positions of every synchronisation marker."""
    positions: list[int] = []
    for index, locals_ in enumerate(SCENE_MARKER_FRAMES):
        base = scene_offset(index)
        positions.extend(base + local for local in locals_)
    return sorted(positions)


def marker_times() -> list[float]:
    """Marker positions in seconds."""
    return [frame / FPS for frame in marker_frames()]


def total_frames() -> int:
    """Total length of the reference timeline in frames."""
    return sum(SCENE_FRAMES)


def _palette(channel: ChannelConfig) -> tuple[tuple[int, int, int], ...]:
    """Four brand colours, in the order the synthetic drawer expects."""
    return tuple(
        channel.brand.palette.as_rgb(name)
        for name in ("deep_indigo", "crt_amber", "parchment_cream", "vermilion")
    )


def generate_reference_assets(workspace: Workspace, channel: ChannelConfig) -> dict[str, Path]:
    """Generate every original asset the reference fixture needs.

    Returns a mapping of logical name to path. Generation is deterministic, so
    repeated builds produce identical checksums and therefore identical cache
    keys.
    """
    directory = workspace.fixtures_dir / "reference"
    directory.mkdir(parents=True, exist_ok=True)
    brand = channel.brand
    palette = _palette(channel)

    primary = still_fixtures.resolve_font("Space Grotesk")
    secondary = still_fixtures.resolve_font("IBM Plex Serif")

    produced: dict[str, Path] = {}

    produced["title_card"] = still_fixtures.generate_title_card(
        directory / "still-title-card.png",
        brand,
        primary_font=primary,
        accent_font=secondary,
    )
    produced["test_pattern_4x3"] = still_fixtures.generate_test_pattern(
        directory / "still-test-pattern-4x3.png", brand
    )
    produced["closing_card"] = still_fixtures.generate_closing_card(
        directory / "still-closing-card.png",
        brand,
        primary_font=primary,
        headline="ENGINEERING REFERENCE",
        subline="Synthetic fixtures - not an episode, not approved",
    )

    # Two more original stills at different geometries, to exercise fitting.
    produced["panel_square"] = _generate_geometric_panel(
        directory / "still-panel-square.png", channel, width=1024, height=1024, seed=3
    )
    produced["panel_wide"] = _generate_geometric_panel(
        directory / "still-panel-wide.png", channel, width=2560, height=1080, seed=7
    )

    # Synthetic video: 4:3 at 24 fps without audio, widescreen at 25 fps with
    # audio, and a small low-resolution clip to exercise upscaling.
    produced["video_4x3"] = generate_synthetic_video(
        directory / "video-4x3-24fps.mp4",
        width=640,
        height=480,
        fps=24,
        frames=24 * 12,
        palette=palette,
        with_audio=False,
    ).path
    produced["video_wide"] = generate_synthetic_video(
        directory / "video-wide-25fps.mp4",
        width=1280,
        height=720,
        fps=25,
        frames=25 * 12,
        palette=palette,
        with_audio=True,
    ).path
    produced["video_small"] = generate_synthetic_video(
        directory / "video-small-15fps.mp4",
        width=480,
        height=360,
        fps=15,
        frames=15 * 10,
        palette=palette,
        with_audio=False,
    ).path

    # Narration surrogates: one tone per scene, each with a click at its start
    # so the audio marker lines up with the scene's visual marker.
    for index, frames in enumerate(SCENE_FRAMES):
        name = f"narration_{index + 1:02d}"
        # Narration is deliberately shorter than its scene, so the timeline
        # exercises "visual time after narration ends" rather than a tight fit.
        duration = (frames - 120) / FPS
        local_markers = SCENE_MARKER_FRAMES[index]
        produced[name] = generate_marker_audio(
            directory / f"narration-{index + 1:02d}.wav",
            duration_seconds=duration,
            sample_rate=SAMPLE_RATE,
            marker_samples=tuple(int(local * SAMPLE_RATE / FPS) for local in local_markers),
            base_frequency=180.0 + 18.0 * index,
            base_amplitude=0.22,
        )

    produced["music_bed"] = generate_marker_audio(
        directory / "music-bed.wav",
        duration_seconds=total_frames() / FPS,
        sample_rate=SAMPLE_RATE,
        marker_samples=(),
        base_frequency=98.0,
        base_amplitude=0.16,
    )

    return produced


def _generate_geometric_panel(
    path: Path,
    channel: ChannelConfig,
    *,
    width: int,
    height: int,
    seed: int,
) -> Path:
    """Draw an original geometric still at an arbitrary geometry.

    Deterministic from ``seed``: a fixed-step pattern, not a random one, so
    repeated builds hash identically.
    """
    from PIL import Image, ImageDraw

    background, accent, light, warn = _palette(channel)
    image = Image.new("RGB", (width, height), background)
    draw = ImageDraw.Draw(image)

    step = max(16, min(width, height) // (6 + seed % 5))
    for index, position in enumerate(range(0, max(width, height), step)):
        colour = (accent, light, warn)[(index + seed) % 3]
        # Nested diamonds, drawn as rotated squares via polygon points.
        draw.line([(position, 0), (0, position)], fill=colour, width=max(2, step // 10))
        draw.line(
            [(width - position, height), (width, height - position)],
            fill=colour,
            width=max(2, step // 10),
        )

    inset = min(width, height) // 8
    draw.rectangle(
        [(inset, inset), (width - inset, height - inset)],
        outline=light,
        width=max(3, step // 8),
    )
    centre = min(width, height) // 5
    draw.rectangle(
        [
            (width // 2 - centre, height // 2 - centre),
            (width // 2 + centre, height // 2 + centre),
        ],
        outline=warn,
        width=max(3, step // 8),
    )

    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, format="PNG")
    return path


def _marker_overlay(scene_index: int, local_frame: int) -> Overlay:
    """A magenta sync marker as a colour panel in the top-left corner."""
    return Overlay(
        overlay_id=f"marker-{scene_index + 1:02d}-{local_frame:04d}",
        kind=OverlayKind.COLOR_PANEL,
        span=FrameSpan(start_frame=local_frame, duration_frames=6),
        anchor=Anchor.TOP_LEFT,
        offset_x_px=-96,
        offset_y_px=-54,
        fill_color="#FF00FF",
        width_fraction=0.06,
        height_fraction=0.10,
    )


