"""The M0.2 engineering reference fixture: an original ~180-second benchmark.

This exists to exercise and measure the composition engine, and to give a human
something to look at when judging whether the output is technically correct. It
is **not** a Polymation episode: the narration is a synthetic tone, not speech,
and the on-screen copy says so.

Every asset is generated by this module — geometric stills drawn with Pillow,
synthetic video encoded from Pillow frames, and arithmetic audio. No third-party
game or anime media is used or required, and nothing here touches the network.

Synchronisation markers: scenes carry a magenta block in the top-left corner on
exactly known frames, and the audio carries a short click at the corresponding
sample. :func:`marker_times` reports those positions so a test can extract the
frame and measure the audio envelope at each one and detect drift either way.
"""

