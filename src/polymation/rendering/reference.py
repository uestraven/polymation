def _build_audio(asset_ids: dict[str, str]) -> AudioMix:
    """Narration per scene plus a ducked music bed under the whole timeline."""
    segments: list[AudioSegment] = []

    for index, frames in enumerate(SCENE_FRAMES):
        start_frame = scene_offset(index)
        duration_frames = frames - 120
        segments.append(
            AudioSegment(
                segment_id=f"narration-{index + 1:02d}",
                role=AudioRole.NARRATION,
                asset_id=asset_ids[f"narration_{index + 1:02d}"],
                span=SampleSpan(
                    start_sample=start_frame * (SAMPLE_RATE // FPS),
                    duration_samples=duration_frames * (SAMPLE_RATE // FPS),
                ),
                fade_in_samples=SAMPLE_RATE // 20,
                fade_out_samples=SAMPLE_RATE // 10,
            )
        )

    segments.append(
        AudioSegment(
            segment_id="music-01",
            role=AudioRole.MUSIC,
            asset_id=asset_ids["music_bed"],
            span=SampleSpan(
                start_sample=0,
                duration_samples=total_frames() * (SAMPLE_RATE // FPS),
            ),
            gain_db=-4.0,
            fade_in_samples=2 * SAMPLE_RATE,
            fade_out_samples=3 * SAMPLE_RATE,
        )
    )

    return AudioMix(
        segments=segments,
        ducking=Ducking(
            enabled=True,
            attenuation_db=-13.0,
            attack_samples=SAMPLE_RATE // 10,
            release_samples=SAMPLE_RATE // 3,
            lead_in_samples=SAMPLE_RATE // 5,
            lead_out_samples=SAMPLE_RATE // 4,
        ),
        loudness=LoudnessTarget(integrated_lufs=-16.0, true_peak_dbtp=-1.0),
        export_stems=True,
    )


def _caption_text() -> str:
    """An SRT document covering the reference timeline.

    Deliberately includes punctuation and non-ASCII characters that would need
    escaping if captions were drawn by FFmpeg's drawtext — apostrophes, colons,
    percent signs, an em dash and accented vowels.
    """
    cues: list[tuple[int, int, str]] = []
    for index in range(len(SCENE_FRAMES)):
        start = scene_offset(index) + 45
        cues.append(
            (
                start,
                start + 150,
                f"Scene {index + 1}: composition engine check",
            )
        )
        cues.append(
            (
                start + 180,
                start + 330,
                'Punctuation: it\'s 100% — "quoted", colon: ok, éèê',
            )
        )

    from polymation.captions.srt import frames_to_timestamp

    blocks: list[str] = []
    for number, (start, end, text) in enumerate(cues, start=1):
        blocks.append(
            f"{number}\n"
            f"{frames_to_timestamp(start, FPS)} --> {frames_to_timestamp(end, FPS)}\n"
            f"{text}"
        )
    return "\n\n".join(blocks) + "\n"


def build_reference_fixture(
    workspace: Workspace,
    channel: ChannelConfig,
    *,
    profile: RenderProfile = FINAL_PROFILE,
    recreate: bool = False,
) -> ReferenceBuild:
    """Build the reference project: generate assets, import them, write a timeline.

    Raises:
        ProjectExistsError: if the project exists and ``recreate`` is false.
    """
    store = ProjectStore(workspace)
    project_root = workspace.project_dir(REFERENCE_PROJECT_ID)
    recreated = False

    if project_root.exists():
        if not recreate:
            raise ProjectExistsError(REFERENCE_PROJECT_ID)
        _remove_reference_project(workspace)
        recreated = True

    produced = generate_reference_assets(workspace, channel)

    try:
        bundle = _assemble_reference_project(store, channel, produced, profile)
    except BaseException:
        _remove_reference_project(workspace)
        raise

    return ReferenceBuild(
        bundle=bundle,
        generated_assets=list(produced.values()),
        recreated=recreated,
    )


def _assemble_reference_project(
    store: ProjectStore,
    channel: ChannelConfig,
    produced: dict[str, Path],
    profile: RenderProfile,
) -> ProjectBundle:
    """Create the project, import assets, and write script, storyboard, timeline."""
    bundle = store.create(
        title=REFERENCE_TITLE,
        project_id=REFERENCE_PROJECT_ID,
        channel_id=channel.channel_id,
        content_pillar=ContentPillar.DESIGN_CRAFT_BREAKDOWN,
        primary_subject=PrimarySubject.INDUSTRY_HISTORY,
        content_format=ContentFormat.STANDARD,
        target_duration_seconds=total_frames() // FPS,
        slug=REFERENCE_SLUG,
        language=channel.brand.language,
    )

    categories: dict[str, AssetCategory] = {
        "title_card": AssetCategory.GRAPHICS,
        "test_pattern_4x3": AssetCategory.GRAPHICS,
        "closing_card": AssetCategory.GRAPHICS,
        "panel_square": AssetCategory.GRAPHICS,
        "panel_wide": AssetCategory.GRAPHICS,
        "video_4x3": AssetCategory.FOOTAGE,
        "video_wide": AssetCategory.FOOTAGE,
        "video_small": AssetCategory.FOOTAGE,
        "music_bed": AssetCategory.MUSIC,
    }

    asset_ids: dict[str, str] = {}
    for name, path in produced.items():
        category = categories.get(name, AssetCategory.NARRATION)
        result = import_asset(
            bundle,
            path,
            category=category,
            original_source=f"polymation.rendering.reference ({path.name})",
            rights_basis=RightsBasis.ORIGINAL_WORK,
            rights_holder="Polymation Studio",
            intended_editorial_use=(
                "Original synthetic asset for the M0.2 engineering reference fixture."
            ),
            ai_generated=False,
        )
        asset_ids[name] = result.asset.asset_id

    # A script, so the project is coherent. Narration stays draft: these are
    # tones, not approved editorial writing.
    bundle.script.scenes = [
        NarrationScene(
            scene_id=f"scene-{index + 1:02d}",
            order=index,
            narration=(
                f"Scene {index + 1} narration surrogate. Synthetic tone with a "
                f"synchronisation click; not speech."
            ),
            status=NarrationStatus.DRAFT,
            estimated_duration_seconds=(frames - 120) / FPS,
        )
        for index, frames in enumerate(SCENE_FRAMES)
    ]
    bundle.script.editorial_notes = [
        "Engineering benchmark. Narration is a synthetic tone, not intelligible "
        "speech, and must never be presented as narration.",
    ]
    bundle.script.touch()

    captions_path = bundle.root / "captions" / "reference.srt"
    captions_path.parent.mkdir(parents=True, exist_ok=True)
    captions_path.write_text(_caption_text(), encoding="utf-8")

    now = utc_now()
    timeline = CompositionTimeline(
        project_id=bundle.project_id,
        profile_name=profile.name.value,
        fps=FPS,
        width=FINAL_PROFILE.width,
        height=FINAL_PROFILE.height,
        audio_sample_rate=SAMPLE_RATE,
        scenes=_build_scenes(asset_ids),
        audio=_build_audio(asset_ids),
        captions=CaptionSettings(
            srt_path="captions/reference.srt",
            burn_in=True,
            export_sidecar=True,
            placement=CaptionPlacement(),
        ),
        created_at=now,
        updated_at=now,
    )

    expected = total_frames()
    if timeline.total_frames != expected:  # pragma: no cover - guards the constants
        raise ValueError(
            f"reference timeline is {timeline.total_frames} frames but SCENE_FRAMES "
            f"sums to {expected}; the scene shot layout and SCENE_FRAMES disagree"
        )

    bundle.timeline = timeline
    bundle.manifest.production_stage = ProductionStage.RENDER
    bundle.save(operation="build reference fixture")
    return bundle


def _remove_reference_project(workspace: Workspace) -> None:
    """Delete the reference project tree.

    Hard-scoped to the fixed reference identifier, so no operator project can be
    destroyed by ``--recreate``.
    """
    import shutil

    target = workspace.project_dir(REFERENCE_PROJECT_ID)
    expected = (workspace.projects_dir / REFERENCE_PROJECT_ID).resolve()

    if target.exists() and target.resolve() != expected:  # pragma: no cover
        raise ProjectExistsError(REFERENCE_PROJECT_ID)

    if target.is_dir():
        shutil.rmtree(target)
